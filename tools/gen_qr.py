#!/usr/bin/env python3
"""Dev-time QR generator: writes res/drawable/qr_donate.xml (vector, no runtime library).
Usage: python3 tools/gen_qr.py <url> [out.xml]"""
import sys, qrcode
url = sys.argv[1]
out = sys.argv[2] if len(sys.argv) > 2 else "app/src/main/res/drawable/qr_donate.xml"
q = qrcode.QRCode(error_correction=qrcode.constants.ERROR_CORRECT_M, border=0)
q.add_data(url); q.make(fit=True)
m = q.get_matrix(); n = len(m); b = 2  # 2-module white quiet zone baked in
size = n + 2 * b
paths = []
for y, row in enumerate(m):
    x = 0
    while x < n:
        if row[x]:
            s = x
            while x < n and row[x]: x += 1
            paths.append(f"M{s+b},{y+b}h{x-s}v1h-{x-s}z")
        else: x += 1
open(out, "w").write(f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/gen_qr.py for {url}. Do not edit by hand. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{size}dp" android:height="{size}dp"
    android:viewportWidth="{size}" android:viewportHeight="{size}">
    <path android:fillColor="#FFFFFF" android:pathData="M0,0h{size}v{size}h-{size}z"/>
    <path android:fillColor="#000000" android:pathData="{''.join(paths)}"/>
</vector>
''')
print("modules", n, "->", out)
